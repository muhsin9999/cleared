// Screenshots the third UI pass: ring, new-sale check and fix, invoice send, activity search, settings. Usage: node scripts/spikes/pass3.mjs <outdir>
import { chromium } from "@playwright/test";
const out = process.argv[2];
const b = await chromium.launch({ executablePath: `${process.env.HOME}/.cache/ms-playwright/chromium-1248/chrome-linux64/chrome` });
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 2 });
const p = await ctx.newPage();
await p.goto("http://localhost:3000"); await p.waitForTimeout(9000);
await p.locator("svg.-rotate-90").first().locator("..").screenshot({ path: `${out}/1-ring.png` });
await p.getByRole("button", { name: /try the live demo/i }).first().click(); await p.waitForURL("**/home");
await p.goto("http://localhost:3000/sales/new");
await p.getByRole("button", { name: /character sheet for a game studio/i }).click();
await p.getByRole("button", { name: /check this sale/i }).click();
await p.waitForTimeout(2600); await p.screenshot({ path: `${out}/2-check-working.png` });
await p.waitForTimeout(2400); await p.screenshot({ path: `${out}/3-check-thinking.png` });
await p.getByRole("button", { name: /create invoice/i }).first().waitFor({ timeout: 30000 }); await p.waitForTimeout(800);
await p.screenshot({ path: `${out}/4-fix.png`, fullPage: true });
await p.getByRole("button", { name: /checks/i }).click(); await p.waitForTimeout(500);
await p.getByRole("button", { name: /fix all/i }).click(); await p.waitForTimeout(1200);
await p.screenshot({ path: `${out}/5-fixed.png`, fullPage: true });
await p.getByRole("button", { name: /create invoice/i }).first().click(); await p.waitForURL("**/invoice", { timeout: 30000 }); await p.getByText("Total due").waitFor(); await p.waitForTimeout(800);
await p.screenshot({ path: `${out}/6-invoice.png` });
await p.goto("http://localhost:3000/activity"); await p.waitForTimeout(1500); await p.screenshot({ path: `${out}/7-activity.png` });
await p.getByRole("searchbox").fill("dispute"); await p.waitForTimeout(400); await p.screenshot({ path: `${out}/8-activity-search.png` });
await p.goto("http://localhost:3000/settings"); await p.waitForTimeout(1200); await p.screenshot({ path: `${out}/9-settings.png` });
const ph = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, storageState: await ctx.storageState() });
const pp = await ph.newPage();
await pp.goto("http://localhost:3000/sales/new?sample=1"); await pp.getByRole("button", { name: /check this sale/i }).click();
await pp.getByRole("button", { name: /create invoice/i }).first().waitFor({ timeout: 30000 }); await pp.waitForTimeout(800);
await pp.screenshot({ path: `${out}/10-phone-fix.png`, fullPage: true });
console.log("done"); await b.close();
