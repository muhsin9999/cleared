// Disputes v1 sandbox loop: create (as buyer) → require-evidence → provide-evidence (PDF) → adjudicate.
// node 05-dispute.mjs create <transactionId>
// node 05-dispute.mjs list               (disputes opened by the sandbox buyer in the PayPal UI)
// node 05-dispute.mjs run <disputeId>
// Creating via API needs the DISPUTE_CREATE scope, which only a PayPal account manager can add.
import { pp, step } from "./paypal.mjs";
const [cmd, arg] = process.argv.slice(2);
const b64u = (o) => Buffer.from(JSON.stringify(o)).toString("base64url");
const buyerAssertion = `${b64u({ alg: "none" })}.${b64u({ iss: process.env.PAYPAL_CLIENT_ID, email: process.env.PAYPAL_SANDBOX_BUYER_EMAIL })}.`;
const wait = (ms) => new Promise((r) => setTimeout(r, ms));

function minimalPdf(lines) {
  const text = lines.map((l, i) => `BT /F1 12 Tf 72 ${720 - i * 18} Td (${l.replace(/[()\\]/g, "")}) Tj ET`).join("\n");
  const objs = ["<< /Type /Catalog /Pages 2 0 R >>", "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
    "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>",
    `<< /Length ${text.length} >>\nstream\n${text}\nendstream`, "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>"];
  let out = "%PDF-1.4\n"; const offs = [];
  objs.forEach((o, i) => { offs.push(out.length); out += `${i + 1} 0 obj\n${o}\nendobj\n`; });
  const xref = out.length;
  out += `xref\n0 ${objs.length + 1}\n0000000000 65535 f \n${offs.map((o) => String(o).padStart(10, "0") + " 00000 n \n").join("")}`;
  return out + `trailer\n<< /Size ${objs.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF\n`;
}

async function status(id) { return (await pp("GET", `/v1/customer/disputes/${id}`)).json; }

if (cmd === "create") {
  const form = new FormData();
  form.append("input", new Blob([JSON.stringify({
    disputed_transactions: [{ buyer_transaction_id: arg }], reason: "MERCHANDISE_OR_SERVICE_NOT_RECEIVED",
    dispute_amount: { currency_code: "USD", value: "40.00" }, buyer_requested_amount: { currency_code: "USD", value: "40.00" },
    dispute_flow: "PAYPAL", extensions: { buyer_contacted_time: new Date().toISOString() }, notes: "Never received the character sheet.",
  })], { type: "application/json" }));
  const { json } = await pp("POST", "/v1/customer/disputes", { raw: form, headers: { "PayPal-Auth-Assertion": buyerAssertion } });
  step("dispute created (sandbox, as buyer)", true, JSON.stringify(json).slice(0, 300));
} else if (cmd === "list") {
  const { json } = await pp("GET", "/v1/customer/disputes?page_size=10");
  for (const x of json.items ?? []) console.log(x.dispute_id, x.status, x.dispute_life_cycle_stage ?? "", x.reason, x.dispute_amount?.value, x.create_time);
  if (!json.items?.length) console.log("no disputes yet");
} else if (cmd === "run") {
  let d = await status(arg);
  step("dispute fetched", true, `${d.dispute_id} ${d.status} stage=${d.dispute_life_cycle_stage} due=${d.seller_response_due_date}`);
  const has = (rel) => d.links.some((l) => l.rel === rel);
  if (d.dispute_life_cycle_stage === "INQUIRY" && has("escalate")) {
    await pp("POST", `/v1/customer/disputes/${arg}/escalate`, { body: { note: "Escalating to test the evidence flow (sandbox)." } });
    for (let i = 0; i < 10 && d.dispute_life_cycle_stage === "INQUIRY"; i++) { await wait(3000); d = await status(arg); }
    step("escalate inquiry → claim", d.dispute_life_cycle_stage !== "INQUIRY", `${d.status} stage=${d.dispute_life_cycle_stage}`);
  }
  if (d.status !== "WAITING_FOR_SELLER_RESPONSE" && !has("provide_evidence") && has("require_evidence")) {
    await pp("POST", `/v1/customer/disputes/${arg}/require-evidence`, { body: { action: "SELLER_EVIDENCE" } });
    for (let i = 0; i < 10 && d.status !== "WAITING_FOR_SELLER_RESPONSE"; i++) { await wait(3000); d = await status(arg); }
    step("require-evidence → WAITING_FOR_SELLER_RESPONSE", d.status === "WAITING_FOR_SELLER_RESPONSE", `${d.status} stage=${d.dispute_life_cycle_stage}`);
  }
  console.log("links:", d.links.map((l) => l.rel).join(", "));
  if (!d.links.some((l) => l.rel === "provide_evidence")) { step("provide-evidence link present", false, "PayPal does not allow evidence in this state"); process.exit(1); }
  const form = new FormData();
  form.append("input", new Blob([JSON.stringify({ evidences: [{ evidence_type: "PROOF_OF_FULFILLMENT",
    notes: "Client accepted the delivered files on the Cleared acceptance page. See exhibit A." }] })], { type: "application/json" }));
  const pdf = minimalPdf(["Exhibit A - Delivery and acceptance record", "Sale: Character sheet commission, USD 40.00",
    "Delivered: character-sheet-final.png (2048x2048)", "Client clicked 'I received the work' - timestamp recorded", "Generated by Cleared (sandbox test)"]);
  form.append("evidence-file", new Blob([pdf], { type: "application/pdf" }), "exhibit-a.pdf");
  try {
    const r = await pp("POST", `/v1/customer/disputes/${arg}/provide-evidence`, { raw: form });
    step("provide-evidence with PDF", true, `HTTP ${r.status}`);
  } catch (e) { step("provide-evidence with PDF", false, e.message.slice(0, 400)); }
  d = await status(arg);
  console.log("after evidence:", d.status, d.dispute_life_cycle_stage, "evidences:", (d.evidences ?? []).length);
  for (let i = 0; i < 10 && !d.links.some((l) => l.rel === "adjudicate"); i++) { await wait(3000); d = await status(arg); }
  console.log("links now:", d.links.map((l) => l.rel).join(", "));
  try {
    await pp("POST", `/v1/customer/disputes/${arg}/adjudicate`, { body: { adjudication_outcome: "SELLER_FAVOR" } });
    for (let i = 0; i < 10 && d.status !== "RESOLVED"; i++) { await wait(3000); d = await status(arg); }
    step("adjudicate SELLER_FAVOR → RESOLVED", d.status === "RESOLVED", `${d.status} outcome=${d.dispute_outcome?.outcome_code}`);
  } catch (e) { step("adjudicate", false, e.message.slice(0, 400)); }
}
