// Review bugs on /sales/new (3 Nov): price field, Fix all stacking, draft kept after a missing client. Usage: node … <outdir>
import { chromium } from "@playwright/test";
const out = process.argv[2];
const BASE = process.env.BASE_URL ?? "http://localhost:3100";
const browser = await chromium.launch({ executablePath: `${process.env.HOME}/.cache/ms-playwright/chromium-1248/chrome-linux64/chrome` });
const page = await (await browser.newContext({ viewport: { width: 1280, height: 900 } })).newPage();
const ok = (cond, msg) => console.log(cond ? "PASS" : "FAIL", msg);
await page.goto(BASE);
await page.getByRole("button", { name: /try the live demo/i }).first().click();
await page.waitForURL("**/home", { timeout: 60_000 });
await page.goto(`${BASE}/sales/new`);
await page.waitForLoadState("networkidle");
await page.locator("#amount").waitFor();
await page.waitForTimeout(800);
const amount = page.locator("#amount");
await amount.pressSequentially("12.5");
ok((await amount.inputValue()) === "12.5", `price "12.5" stays as typed (got "${await amount.inputValue()}")`);
await amount.fill("-50");
ok(await page.getByText(/Enter a price above \$0/).isVisible(), "a negative price shows an error");
ok(await page.getByRole("button", { name: "Check this sale" }).isDisabled(), "and the check can't start");
await page.screenshot({ path: `${out}/1-negative-price.png` });
await amount.fill("400");
await page.locator("#title").fill("Character sheet: 3 poses");
await page.locator("#description").fill("Character sheet for our game's main hero");
await page.getByRole("button", { name: "Check this sale" }).click();
await page.getByRole("heading", { name: /To fix|Nothing left/ }).waitFor({ timeout: 60_000 });
const fixAll = page.getByRole("button", { name: /Fix all/ });
console.log("before:", await fixAll.innerText());
await fixAll.click();
await page.waitForTimeout(600);
const heading = await page.getByRole("heading", { name: /To fix|Nothing left/ }).innerText();
ok(!(await fixAll.isVisible().catch(() => false)) && /Nothing left|To fix \((0|1)\)/.test(heading), `one press of Fix all clears every fixable item ("${heading}")`);
await page.screenshot({ path: `${out}/2-after-fix-all.png`, fullPage: true });
await page.getByRole("button", { name: "Create invoice" }).first().click();
await page.locator("#clientName").waitFor({ timeout: 30_000 });
await page.waitForTimeout(500);
const desc = await page.locator("#description").inputValue();
ok((await page.locator("#title").inputValue()) === "Character sheet: 3 poses", "title kept after the missing-client bounce");
ok((await amount.inputValue()) === "400", "price kept");
ok(desc.includes("Delivered as PNG") && desc.includes("commercially"), `description kept with both fixes: "${desc}"`);
ok(await page.getByText("Add the client’s name").isVisible(), "missing client name is flagged");
await page.screenshot({ path: `${out}/3-back-to-describe.png`, fullPage: true });
await browser.close();
